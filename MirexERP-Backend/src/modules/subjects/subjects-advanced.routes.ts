import {Router} from "express";
import {z} from "zod";
import {authenticate} from "../../middleware/authenticate";
import {authorize} from "../../middleware/authorize";
import {tenantContext,requireTenant} from "../../middleware/tenantContext";
import {validate} from "../../middleware/validate";
import {schoolDocumentUploader} from "../../utils/fileStorage";
import {USER_ROLES} from "../../config/constants";
import {mappingSchema,teacherAssignmentSchema,electiveSchema,syllabusSchema,updateSyllabusSchema,advancedFilters,advancedId} from "./subjects-advanced.validation";
import * as c from "./subjects-advanced.controller";
const router=Router();
const zodElectiveQuery=z.object({sessionId:z.string().regex(/^[0-9a-fA-F]{24}$/),classId:z.string().regex(/^[0-9a-fA-F]{24}$/)});
const zodStudentParam=z.object({studentId:z.string().regex(/^[0-9a-fA-F]{24}$/)});
const zodSessionQuery=z.object({sessionId:z.string().regex(/^[0-9a-fA-F]{24}$/),classId:z.string().regex(/^[0-9a-fA-F]{24}$/).optional()});
const admins=[USER_ROLES.SUPER_ADMIN,USER_ROLES.SCHOOL_ADMIN,USER_ROLES.PRINCIPAL] as const;
router.use(authenticate,tenantContext,requireTenant);
router.get("/reports/summary",authorize(...admins),validate({query:advancedFilters}),c.subjectAdvancedSummary);
router.get("/reports/class-wise",authorize(...admins),validate({query:advancedFilters}),c.subjectClassWiseReport);
router.get("/reports/teacher-wise",authorize(...admins),validate({query:advancedFilters}),c.subjectTeacherWiseReport);
router.get("/class-mappings",authorize(...admins),validate({query:advancedFilters}),c.subjectMappings);
router.post("/class-mappings",authorize(...admins),validate({body:mappingSchema}),c.createSubjectMapping);
router.put("/class-mappings/:id",authorize(...admins),validate({params:advancedId,body:mappingSchema}),c.updateSubjectMapping);
router.delete("/class-mappings/:id",authorize(...admins),validate({params:advancedId}),c.deleteSubjectMapping);
router.get("/teacher/my-assignments",authorize(USER_ROLES.TEACHER),c.myTeacherSubjectAssignments);
router.get("/teacher/my-syllabus",authorize(USER_ROLES.TEACHER),c.myTeacherSyllabi);
router.get("/teacher-assignments",authorize(...admins),validate({query:advancedFilters}),c.teacherAssignments);
router.post("/teacher-assignments",authorize(...admins),validate({body:teacherAssignmentSchema}),c.createTeacherAssignment);
router.put("/teacher-assignments/:id",authorize(...admins),validate({params:advancedId,body:teacherAssignmentSchema}),c.updateTeacherAssignment);
router.delete("/teacher-assignments/:id",authorize(...admins),validate({params:advancedId}),c.deleteTeacherAssignment);
router.get("/electives/available",authorize(...admins),validate({query:zodElectiveQuery}),c.availableElectives);
router.get("/electives/student/:studentId",authorize(...admins),validate({params:zodStudentParam,query:zodSessionQuery}),c.studentElectives);
router.post("/electives/select",authorize(...admins),validate({body:electiveSchema}),c.selectStudentElectives);
router.delete("/electives/:id",authorize(...admins),validate({params:advancedId}),c.removeStudentElective);
router.get("/syllabus",authorize(...admins),validate({query:advancedFilters}),c.subjectSyllabi);
router.post("/syllabus",authorize(...admins),validate({body:syllabusSchema}),c.createSubjectSyllabus);
router.post("/syllabus/upload",authorize(...admins),schoolDocumentUploader.single("file"),c.uploadSubjectSyllabus);
router.put("/syllabus/:id",authorize(...admins),validate({params:advancedId,body:updateSyllabusSchema}),c.updateSubjectSyllabus);
router.put("/syllabus/:id/upload",authorize(...admins),validate({params:advancedId}),schoolDocumentUploader.single("file"),c.replaceSubjectSyllabusFile);
router.get("/syllabus/:id/download",authorize(...admins),validate({params:advancedId}),c.downloadSubjectSyllabus);
router.delete("/syllabus/:id",authorize(...admins),validate({params:advancedId}),c.deleteSubjectSyllabus);
export default router;
