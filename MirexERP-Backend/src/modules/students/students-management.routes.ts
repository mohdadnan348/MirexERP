import { Router } from "express";
import { authenticate } from "../../middleware/authenticate";
import { authorize } from "../../middleware/authorize";
import { tenantContext, requireTenant } from "../../middleware/tenantContext";
import { studentDocumentUploader, studentPhotoUploader } from "../../utils/fileStorage";
import * as controller from "./students-management.controller";

const router = Router();
router.use(authenticate, tenantContext, requireTenant);
const readRoles = ["SCHOOL_ADMIN", "PRINCIPAL", "TEACHER", "ACCOUNTANT", "RECEPTIONIST"];
const manageRoles = ["SCHOOL_ADMIN", "PRINCIPAL", "RECEPTIONIST"];
router.get("/my-children", authorize(["PARENT"]), controller.myChildren);
router.get("/reports", authorize(["SCHOOL_ADMIN", "PRINCIPAL", "ACCOUNTANT"]), controller.reports);
router.get("/:id/tc/print", authorize(["SCHOOL_ADMIN", "PRINCIPAL"]), controller.downloadTc);
router.get("/:id/records", authorize(manageRoles), controller.records);
router.post("/:id/photo", authorize(manageRoles), studentPhotoUploader.single("file"), controller.uploadPhoto);
router.get("/:id/photo", authorize(readRoles), controller.getPhoto);
router.post("/:id/documents", authorize(manageRoles), studentDocumentUploader.single("file"), controller.uploadDocument);
router.get("/:id/documents/:documentId/download", authorize(manageRoles), controller.downloadDocument);
router.put("/:id/documents/:documentId", authorize(manageRoles), studentDocumentUploader.single("file"), controller.replaceDocument);
router.patch("/:id/documents/:documentId/verify", authorize(["SCHOOL_ADMIN", "PRINCIPAL", "RECEPTIONIST"]), controller.verifyDocument);
router.delete("/:id/documents/:documentId", authorize(["SCHOOL_ADMIN", "PRINCIPAL"]), controller.deleteDocument);
router.put("/:id/medical", authorize(["SCHOOL_ADMIN", "PRINCIPAL"]), controller.medicalPut);
router.put("/:id/previous-school", authorize(manageRoles), controller.previousSchoolPut);
router.get("/:id/medical", authorize(["SCHOOL_ADMIN", "PRINCIPAL"]), controller.medicalGet);
router.post("/:id/transfer", authorize(["SCHOOL_ADMIN", "PRINCIPAL"]), controller.transfer);
router.post("/:id/withdraw", authorize(["SCHOOL_ADMIN", "PRINCIPAL"]), controller.withdraw);
router.post("/:id/alumni", authorize(["SCHOOL_ADMIN", "PRINCIPAL"]), controller.markAlumni);
router.post("/:id/tc", authorize(["SCHOOL_ADMIN", "PRINCIPAL"]), controller.issueTc);
router.post("/:id/promote", authorize(["SCHOOL_ADMIN", "PRINCIPAL"]), controller.promote);
export default router;
