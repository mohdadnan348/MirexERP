import {Router} from "express";
import {authenticate} from "../../middleware/authenticate";
import {tenantContext,requireTenant} from "../../middleware/tenantContext";
import {authorize} from "../../middleware/authorize";
import {USER_ROLES} from "../../config/constants";
import {admissionDocumentUploader} from "../../utils/fileStorage";
import {validate} from "../../middleware/validate";
import {createEnquirySchema,updateEnquirySchema,createEnquiryFollowUpSchema,updateEnquiryFollowUpSchema,transitionAdmissionStatusSchema} from "./admissions.validation";
import {uploadAdmissionDocument,listAdmissionDocuments,verifyAdmissionDocument,downloadAdmissionDocument,replaceAdmissionDocument,deleteAdmissionDocument,transitionApplication,applicationHistory,convertEnquiryToApplication,registrationDetails} from "./admissions-extended.controller";
import {enquiriesList,enquiriesCreate,enquiriesUpdate,enquiriesDelete,followUpCreate,followUpUpdate,followUpsList,reports,settingsGet,settingsPut} from "./admissions-extended.controller";
const router=Router(); router.use(authenticate,tenantContext,requireTenant);
const staff=[USER_ROLES.SCHOOL_ADMIN,USER_ROLES.PRINCIPAL,USER_ROLES.RECEPTIONIST];
router.get("/follow-ups",authorize(...staff),followUpsList);
router.get("/enquiries",authorize(...staff),enquiriesList);
router.post("/enquiries",authorize(...staff),validate(createEnquirySchema),enquiriesCreate);
router.post("/enquiries/:id/convert",authorize(...staff),convertEnquiryToApplication);
router.patch("/enquiries/:id",authorize(...staff),validate(updateEnquirySchema),enquiriesUpdate);
router.delete("/enquiries/:id",authorize(USER_ROLES.SCHOOL_ADMIN,USER_ROLES.PRINCIPAL),enquiriesDelete);
router.post("/enquiries/:id/follow-ups",authorize(...staff),validate(createEnquiryFollowUpSchema),followUpCreate);
router.patch("/enquiries/:id/follow-ups/:followUpId",authorize(...staff),validate(updateEnquiryFollowUpSchema),followUpUpdate);
router.get("/:id/registration",authorize(...staff),registrationDetails);
router.get("/:id/admission-number",authorize(...staff),registrationDetails);
router.get("/:id/history",authorize(...staff),applicationHistory);
router.patch("/:id/status",authorize(...staff),validate(transitionAdmissionStatusSchema),transitionApplication);
router.post("/:id/documents",authorize(...staff),admissionDocumentUploader.single("document"),uploadAdmissionDocument);
router.get("/:id/documents",authorize(...staff),listAdmissionDocuments);
router.patch("/:id/documents/:documentId/verify",authorize(USER_ROLES.SCHOOL_ADMIN,USER_ROLES.PRINCIPAL,USER_ROLES.RECEPTIONIST),verifyAdmissionDocument);
router.put("/:id/documents/:documentId",authorize(...staff),admissionDocumentUploader.single("document"),replaceAdmissionDocument);
router.delete("/:id/documents/:documentId",authorize(USER_ROLES.SCHOOL_ADMIN,USER_ROLES.PRINCIPAL),deleteAdmissionDocument);
router.get("/:id/documents/:documentId/download",authorize(...staff),downloadAdmissionDocument);
router.get("/reports",authorize(USER_ROLES.SCHOOL_ADMIN,USER_ROLES.PRINCIPAL),reports);
router.get("/settings",authorize(USER_ROLES.SCHOOL_ADMIN),settingsGet);
router.put("/settings",authorize(USER_ROLES.SCHOOL_ADMIN),settingsPut);
export default router;
