import { requireSubscriptionFeature } from "../subscriptions/subscription-entitlement.middleware";
import { Router } from "express";
import { authenticate } from "../../middleware/authenticate";
import { tenantContext, requireTenant } from "../../middleware/tenantContext";
import { authorize } from "../../middleware/authorize";
import { libraryReports,getMyLibrary,libraryDashboard,listLibraryCategories,createLibraryCategory,createBookCopies,listBookCopies,getLibrarySettings,updateLibrarySettings,renewLibraryIssue,waiveLibraryFine,libraryStudentHistory } from "./library-operations.controller";
const router=Router();router.use(authenticate,tenantContext,requireTenant);router.use(requireSubscriptionFeature("LIBRARY"));
router.get("/me",authorize("STUDENT","PARENT"),getMyLibrary);
router.get("/reports",authorize("SCHOOL_ADMIN","PRINCIPAL","LIBRARIAN","ACCOUNTANT"),libraryReports);
router.get("/dashboard",authorize("SCHOOL_ADMIN","PRINCIPAL","LIBRARIAN"),libraryDashboard);
router.get("/categories",authorize("SCHOOL_ADMIN","PRINCIPAL","LIBRARIAN","TEACHER"),listLibraryCategories);
router.post("/categories",authorize("SCHOOL_ADMIN","PRINCIPAL","LIBRARIAN"),createLibraryCategory);
router.get("/copies",authorize("SCHOOL_ADMIN","PRINCIPAL","LIBRARIAN","TEACHER"),listBookCopies);
router.post("/copies",authorize("SCHOOL_ADMIN","PRINCIPAL","LIBRARIAN"),createBookCopies);
router.get("/settings",authorize("SCHOOL_ADMIN","PRINCIPAL","LIBRARIAN"),getLibrarySettings);
router.patch("/settings",authorize("SCHOOL_ADMIN","PRINCIPAL"),updateLibrarySettings);
router.post("/issues/:id/renew",authorize("SCHOOL_ADMIN","PRINCIPAL","LIBRARIAN"),renewLibraryIssue);
router.post("/fines/:id/waive",authorize("SCHOOL_ADMIN","PRINCIPAL","LIBRARIAN"),waiveLibraryFine);
router.get("/students/:studentId/history",authorize("SCHOOL_ADMIN","PRINCIPAL","LIBRARIAN","STUDENT"),libraryStudentHistory);
export default router;
